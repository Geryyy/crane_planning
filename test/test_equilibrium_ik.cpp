// The equilibrium-constrained inverse kinematics of `wiki/robot_model.md` 2.2,
// over sampled goal poses per tool, with the **two** oracles this route owes.
//
//   1. the forward-kinematics residual of 2.2, which gates this route exactly as
//      it gates the semi-analytic one -- a converged NLP whose answer does not
//      put the tool where it was asked for is a refusal naming the residual;
//   2. the equilibrium residual against `Model::passive_equilibrium`, which is
//      what makes the answer a genuine steady state and not merely a root of the
//      solver's own constraint.
//
// Both are re-evaluated here through the frozen model API rather than read off
// the residuals the solver reports, because a solver that reports its own
// residual is asserting nothing.
//
// Every sweep case is *generated by* forward kinematics from a configuration the
// description allows, with the passive pair already at the equilibrium of that
// configuration. So each goal is known by construction to have an
// equilibrium solution, and a refusal is a defect rather than a hard pose. The
// one case that deliberately has none is built the other way round and is a test
// of its own.
//
// Offline C++: no ROS, no DDS, no simulator is linked into this binary and none
// is reachable from it.

#include <gtest/gtest.h>

#include <algorithm>
#include <array>
#include <cmath>
#include <cstddef>
#include <iostream>
#include <limits>
#include <random>
#include <string>
#include <vector>

#include "crane_planning/equilibrium_ik.hpp"
#include "description_fixture.hpp"

