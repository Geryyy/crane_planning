/// How close to the slewing axis a sampled goal may be, m.
/**
 * The same exclusion the semi-analytic sweep states and for the same reason:
 * 2.2 step 1 is `q1 = atan2(y_d, x_d)`, which has no value on the axis itself,
 * and this route seeds from that one.
 */
constexpr double kAxisExclusion = 2.0;

/// How many reachable goals each tool is exercised over.
/**
 * Smaller than the semi-analytic sweep's 60 because a solve here costs that
 * one *plus* the NLP it seeds -- this route runs the fast route first. Twenty
 * five per tool is wide enough to catch a redundancy resolved outside the
 * telescope range or a converged solve that landed on the wrong root of
 * `g_u(q) = 0`, and keeps the binary inside its timeout.
 */
constexpr int kSamples = 25;

double wrap(double angle)
{
  return std::remainder(angle, 2.0 * M_PI);
}

double uniform(std::mt19937_64 & source, double lower, double upper)
{
  return std::uniform_real_distribution<double>(lower, upper)(source);
}

/// The actuated projection of a canonical eight-vector.
crane_model::QA actuated_of(const crane_model::Q & q)
{
  crane_model::QA q_a;
  for (std::size_t row = 0; row < crane_model::kActuatedDof; ++row) {
    q_a[static_cast<Eigen::Index>(row)] =
      q[static_cast<Eigen::Index>(crane_planning::kActuatedRows[row])];
  }
  return q_a;
}

/// The canonical eight of one actuated configuration, settled at its equilibrium.
bool settled_configuration(
  const crane_model::Model & model, const crane_model::QA & q_a,
  const crane_model::Payload & payload, crane_model::Q & q)
{
  auto settled = model.passive_equilibrium(q_a, payload);
  if (!settled.ok()) {
    return false;
  }
  q = crane_model::Q::Zero();
  for (std::size_t row = 0; row < crane_model::kActuatedDof; ++row) {
    q[static_cast<Eigen::Index>(crane_planning::kActuatedRows[row])] =
      q_a[static_cast<Eigen::Index>(row)];
  }
  q.segment<2>(4) = settled.value();
  return true;
}

/// A configuration inside the description's own ranges, with a margin.
crane_model::QA sample_configuration(
  std::mt19937_64 & source, const crane_planning::JointLimits & limits, double q8)
{
  crane_model::QA q_a = crane_model::QA::Zero();
  for (std::size_t row = 0; row < 4U; ++row) {
    const crane_planning::AxisLimit & axis = limits.axis[row];
    const double margin = 0.05 * (axis.upper - axis.lower);
    q_a[static_cast<Eigen::Index>(row)] =
      uniform(source, axis.lower + margin, axis.upper - margin);
  }
  q_a[0] = uniform(source, -2.5, 2.5);
  q_a[4] = uniform(source, -2.0, 2.0);
  q_a[5] = q8;
  return q_a;
}

struct Case
{
  crane_model::QA q_a;
  Eigen::Vector3d p_tcp_0;
  double phi_z{};
};

/// The goals one machine is exercised over, each known to have an equilibrium.
std::vector<Case> reachable_goals(
  const crane_model::Model & model, const crane_planning::JointLimits & limits, double q8,
  const crane_model::Payload & payload)
{
  std::mt19937_64 source(20260824U);
  std::vector<Case> cases;
  while (static_cast<int>(cases.size()) < kSamples) {
    Case sample;
    sample.q_a = sample_configuration(source, limits, q8);
    crane_model::Q q;
    if (!settled_configuration(model, sample.q_a, payload, q)) {
      continue;
    }
    auto pose = model.forward_kinematics(
      q, crane_model::Frame::MountingBase, crane_model::Frame::Tcp);
    if (!pose.ok()) {
      continue;
    }
    sample.p_tcp_0 = pose.value().position_m;
    if (sample.p_tcp_0.head<2>().norm() < kAxisExclusion) {
      continue;
    }
    sample.phi_z = crane_planning::phi_z_of(pose.value().orientation);
    cases.push_back(sample);
  }
  return cases;
}

/// An offset grasp: a payload with mass, held off the tilt axis.
/**
 * `wiki/robot_model.md` 5.1 in as many words -- an offset grasp *moves the
 * equilibrium*. A payload whose centre of mass sits on the hanging line adds
 * weight and nothing else, so it is the offset and not the mass alone that makes
 * the tool hang differently, and a test that used a centred one would assert
 * nothing.
 */
crane_model::Payload offset_grasp()
{
  crane_model::Payload payload;
  payload.valid = true;
  payload.mass_kg = 300.0;
  payload.center_of_mass_k8_m = Eigen::Vector3d(0.05, -0.02, 1.1);
  payload.inertia_k8_kg_m2.setZero();
  return payload;
}

